const {test,expect}=require('@playwright/test');
const fs=require('fs');
const base='https://77-eventos-map-v7-demo.on7.workers.dev';
test('worker publicado: homepage, jornada de fã e gestão editável refletida em 3 visões',async({page})=>{
 const errors=[];page.on('pageerror',err=>errors.push(err.message));
 const response=await page.goto(base+'/',{waitUntil:'domcontentloaded',timeout:30000});
 expect(response.status()).toBe(200);
 await page.setViewportSize({width:390,height:844});
 await expect(page.locator('.hero-signature')).toContainText('Melhor pra você, e pro cliente');
 await expect(page.locator('#home table')).toHaveCount(2);
 await expect(page.locator('#home')).toContainText('Orçamentos começam em R$ 100 mensais.');
 await expect(page.locator('#rfb-landing-opp-title')).toHaveText('Feira de criadores ARMY');
 fs.mkdirSync('qa-artifacts',{recursive:true});
 await page.screenshot({path:'qa-artifacts/home-390.png',fullPage:true});
 await page.locator('#hero-public').click();
 await expect(page).toHaveURL(base+'/publico');
 await expect(page.locator('#rfb-opps-public .opp-card')).toHaveCount(3);
 await page.locator('[data-opp-consult]').first().click();
 await expect(page.locator('#message-dialog')).toBeVisible();
 await page.locator('#close-message').click();
 await page.screenshot({path:'qa-artifacts/publico-390.png',fullPage:true});
 await page.goto(base+'/gestao',{waitUntil:'domcontentloaded'});
 await expect(page.locator('#rfb-opps-admin-list .opp-admin-item')).toHaveCount(3);
 const row=page.locator('.opp-admin-item',{hasText:'Feira de criadores ARMY'});
 await row.locator('[data-opp-edit]').click();
 await page.locator('#rfb-opp-title').fill('Feira de criadores atualizada pelo QA');
 await page.locator('#rfb-opp-form button[type="submit"]').click();
 await expect(page.locator('#rfb-opps-admin-list')).toContainText('Feira de criadores atualizada pelo QA');
 await page.screenshot({path:'qa-artifacts/gestao-390.png',fullPage:true});
 await page.goto(base+'/publico',{waitUntil:'domcontentloaded'});
 await expect(page.locator('#rfb-opps-public')).toContainText('Feira de criadores atualizada pelo QA');
 await page.goto(base+'/',{waitUntil:'domcontentloaded'});
 await expect(page.locator('#rfb-landing-opp-title')).toHaveText('Feira de criadores atualizada pelo QA');
 await page.setViewportSize({width:1440,height:900});
 const w=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 expect(w.scroll).toBeLessThanOrEqual(w.width);
 await page.screenshot({path:'qa-artifacts/home-1440.png',fullPage:true});
 expect(errors).toEqual([]);
});
